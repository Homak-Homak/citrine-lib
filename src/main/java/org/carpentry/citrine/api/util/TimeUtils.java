package org.carpentry.citrine.api.util;

public class TimeUtils {

    // Int

    public static int seconds(int seconds){
        return seconds * 20;
    }

    public static int minutes(int minutes){
        return minutes * 1200;
    }

    public static int hours(int hours){
        return hours * 1200 * 60;
    }

    // Floats

    public static float seconds(float seconds){
        return seconds * 20;
    }

    public static float minutes(float minutes){
        return minutes * 1200;
    }

    public static float hours(float hours){
        return hours * 1200 * 60;
    }

    // Longs

    public static long seconds(long seconds){
        return seconds * 20;
    }

    public static long minutes(long minutes){
        return minutes * 1200;
    }

    public static long hours(long hours){
        return hours * 1200 * 60;
    }

    // Doubles

    public static double seconds(double seconds){
        return seconds * 20;
    }

    public static double minutes(double minutes){
        return minutes * 1200;
    }

    public static double hours(double hours){
        return hours * 1200 * 60;
    }
}